import fs from 'node:fs/promises';
import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { IMPLEMENTATIONS, caseDigestsNow, tally } from './conformance-reports.mjs';

const check = process.argv.includes('--check');
const read = async path => JSON.parse(await fs.readFile(path, 'utf8'));
const outputs = new Map();
const itemSchema = await read('schema/context_item.schema.json');
const traceSchema = await read('schema/trace.schema.json');
const profileSchema = await read('schema/profile.schema.json');
const batchSchema = await read('schema/producer_batch.schema.json');
const conflictGroupSchema = await read('schema/conflict_group.schema.json');
const routePolicySchema = await read('schema/route_policy.schema.json');
const snapshotSchema = await read('schema/snapshot.schema.json');
const registryLockSchema = await read('schema/registry_lock.schema.json');
const conformanceReportSchema = await read('schema/conformance_report.schema.json');
const data = {
  ITEM_SCHEMA: itemSchema,
  TRACE_SCHEMA: traceSchema,
  SLOT_DEFAULTS: await read('contract/slot-defaults.json'),
  REASONS: await read('contract/reasons.json'),
  ITEM_EXAMPLE: await read('examples/context-item.json'),
  TRACE_EXAMPLE: await read('examples/trace.json'),
  PROFILES: await read('examples/profiles.json')
};
outputs.set('generated/contract-data.js', '// Generated by npm run build:contract. Edit schema/, contract/, or examples/.\n' +
  Object.entries(data).map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};`).join('\n') + '\n');
const scaffoldFiles = { ASSEMBLY_SKETCH: 'assembly-sketch.txt', PAYLOAD_TEMPLATE: 'payload.txt', AGENT_GUIDE: 'cwa.md' };
const scaffoldText = await Promise.all(Object.entries(scaffoldFiles).map(async ([name, path]) =>
  `export const ${name} = ${JSON.stringify(await fs.readFile('contract/' + path, 'utf8'))};`));
outputs.set('generated/scaffold-text.js', '// Generated by npm run build:contract.\n' + scaffoldText.join('\n') + '\n');
const producers = await fs.readFile('producers.html', 'utf8');
const failures = data.REASONS.filter(r => r.kind === 'exclusion').map(r => [r.code, r.text, Number(r.rule.slice(2))]);
outputs.set('producers.html', producers.replace(/const SLOT_DEFAULTS = \{[\s\S]*?\n\};/,
  `const SLOT_DEFAULTS = ${JSON.stringify(data.SLOT_DEFAULTS, null, 2)};`)
  .replace(/const FAILURES = \[[\s\S]*?\n\];/, `const FAILURES = ${JSON.stringify(failures, null, 2)};`));
const index = await fs.readFile('index.html', 'utf8');
const itemPreview = JSON.stringify(data.ITEM_EXAMPLE, null, 2).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
outputs.set('index.html', index.replace(/<!-- CONTRACT_ITEM_START -->[\s\S]*?<!-- CONTRACT_ITEM_END -->/,
  `<!-- CONTRACT_ITEM_START -->\n<pre style="padding: 20px 18px; overflow: auto; margin: 0;">${itemPreview}</pre>\n<!-- CONTRACT_ITEM_END -->`));

const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv);
ajv.addSchema(itemSchema);
ajv.addSchema(traceSchema);
ajv.addSchema(profileSchema);
ajv.addSchema(batchSchema);
ajv.addSchema(conflictGroupSchema);
ajv.addSchema(routePolicySchema);
ajv.addSchema(snapshotSchema);
ajv.addSchema(registryLockSchema);
ajv.addSchema(conformanceReportSchema);
const source = standalone(ajv, {
  validateItemSchema: itemSchema.$id, validateTraceSchema: traceSchema.$id,
  validateProfileSchema: profileSchema.$id, validateProducerBatchSchema: batchSchema.$id,
  validateConflictGroupSchema: conflictGroupSchema.$id, validateSnapshotSchema: snapshotSchema.$id,
  validateRoutePolicySchema: routePolicySchema.$id, validateRegistryLockSchema: registryLockSchema.$id,
  validateConformanceReportSchema: conformanceReportSchema.$id
});
const bundle = await build({
  stdin: { contents: source, resolveDir: process.cwd(), sourcefile: 'compiled-schemas.js' },
  bundle: true, format: 'esm', platform: 'browser', write: false,
  banner: { js: '// Generated by npm run build:contract. Ajv and ajv-formats: MIT licensed.' }
});
outputs.set('generated/schema-validators.js', bundle.outputFiles[0].text);
const evidence = await fs.readFile('evidence.html', 'utf8');
outputs.set('evidence.html', evidence.replace(/const PROFILES = \[[\s\S]*?\n\];/,
  `const PROFILES = ${JSON.stringify(await read('contract/profile-display.json'), null, 2)};`)
  .replace(/const PROFILE_CONTRACTS = \[[\s\S]*?\];/,
    `const PROFILE_CONTRACTS = ${JSON.stringify(data.PROFILES, null, 2)};`));

// The requirement text is authored once and embedded for static hosting.
const requirements = (await read('contract/requirements.json')).sort((a, b) => Number(a.id.slice(2)) - Number(b.id.slice(2)));
// IDs are permanent: new requirements append, and none is renumbered or reused.
if (requirements.some((rule, index) => rule.id !== `R-${index + 1}`)) throw new Error(`Expected permanent requirement IDs R-1 through R-${requirements.length}.`);
const rules = requirements.map(rule => [rule.section, rule.keyword, rule.summary, rule.text]);
// What a reference assembler can verify for each requirement; drives the Assembler page matrix.
const scopes = await read('contract/assembler-scope.json');
if (scopes.length !== requirements.length || scopes.some((row, index) => row.id !== `R-${index + 1}` || !['assembler', 'boundary', 'application'].includes(row.scope) || !row.note)) {
  throw new Error(`contract/assembler-scope.json needs R-1 through R-${requirements.length} in order, each with a scope and a note.`);
}
// Claims imported from the reference assembler (scripts/import-assembler-status.mjs).
const { requirements: statuses } = await read('contract/assembler-status.json');
const allowed = { assembler: ['planned', 'in progress', 'implemented'], boundary: ['planned', 'in progress', 'boundary-checked'], application: ['documented'] };
statuses.forEach((row, i) => {
  if (row.id !== `R-${i + 1}` || !allowed[scopes[i].scope].includes(row.status)) throw new Error(`contract/assembler-status.json: ${row.id} status ${row.status} does not fit scope ${scopes[i].scope}`);
});
if (statuses.length !== requirements.length) throw new Error(`contract/assembler-status.json needs R-1 through R-${requirements.length}.`);
// Each implementation's conformance run, checked against this repo's own cases: a published case the report
// lacks, reports as anything but passed (rejected, for a rejection case), or ran before its files last changed
// does not count (conformance/README.md, Reporting results).
const caseFiles = async dir => (await fs.readdir(dir).catch(() => [])).sort().map(name => `${dir}/${name}/case.json`);
const digests = await caseDigestsNow();
const published = (await Promise.all([...await caseFiles('conformance/cases'), ...await caseFiles('conformance/rejections')].map(read)))
  .map(c => ({ ...c, digest: digests[c.id] }));
const casesFor = id => published.filter(c => c.rules.includes(id));
const validateReport = ajv.getSchema(conformanceReportSchema.$id);
const runs = await Promise.all(IMPLEMENTATIONS.map(async ({ label, file }) => {
  const { source, cases_at_run: atRun, report } = await read(file);
  if (report === undefined || atRun === undefined) throw new Error(`${file} has no report or cases_at_run; import it with scripts/import-conformance-report.mjs`);
  if (!validateReport(report)) throw new Error(`${file}: ` + JSON.stringify(validateReport.errors));
  return { label, source, report, outcomes: tally(report, atRun, published) };
}));
const conformance = runs.map(({ label, source, report, outcomes }) => ({
  label, name: report.implementation.name, version: report.implementation.version, repository: source.repository,
  commit: source.commit.slice(0, 7), website: report.contract.website_commit.slice(0, 7), total: published.length,
  passed: [...outcomes.values()].filter(o => o === 'passed').length, stale: [...outcomes.values()].filter(o => o === 'stale').length,
}));
for (const page of ['spec.html', 'assembler.html']) {
  const html = await fs.readFile(page, 'utf8');
  const rows = page === 'spec.html' ? rules : rules.map((r, i) => [r[1], r[2], scopes[i].scope, scopes[i].note, statuses[i].status,
    casesFor(`R-${i + 1}`).length, runs.map(run => casesFor(`R-${i + 1}`).filter(c => run.outcomes.get(c.id) === 'passed').length)]);
  let updated = html.replace(/const RULES = \[[\s\S]*?\n\];/, `const RULES = ${JSON.stringify(rows, null, 2)};`);
  if (page === 'assembler.html') updated = updated.replace(/const CONFORMANCE = [\[{][\s\S]*?[\]}];/, `const CONFORMANCE = ${JSON.stringify(conformance)};`);
  if (page === 'spec.html') {
    const profile = JSON.stringify(data.PROFILES[0], null, 2).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
    updated = updated.replace(/<!-- CONTRACT_PROFILE_START -->[\s\S]*?<!-- CONTRACT_PROFILE_END -->/,
      `<!-- CONTRACT_PROFILE_START -->\n          <pre style="padding: 18px; overflow: auto; margin: 0;">${profile}</pre>\n          <!-- CONTRACT_PROFILE_END -->`);
  }
  outputs.set(page, updated);
}
outputs.set('SPEC.md', '# CWA draft — numbered requirements\n\nGenerated from `contract/requirements.json`. The [Spec page](./spec.html) provides the normative definitions and context. Published schemas in `schema/` define JSON field shapes.\n\n' +
  rules.map((r, i) => `## R-${i + 1}: ${r[2]}\n\n${r[3]}\n`).join('\n'));

for (const [path, content] of outputs) {
  if (check) {
    const existing = await fs.readFile(path, 'utf8').catch(() => null);
    if (existing !== content) throw new Error(`${path} is stale; run npm run build:contract`);
  } else await fs.writeFile(path, content);
}
console.log(`${check ? 'Checked' : 'Generated'} ${outputs.size} contract artifacts.`);
