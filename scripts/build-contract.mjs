import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { IMPLEMENTATIONS, caseDigestsNow, ranAt, reportErrors, tally } from './conformance-reports.mjs';
import { specMarkdown } from './spec-markdown.mjs';

const check = process.argv.includes('--check');
const read = async path => JSON.parse(await fs.readFile(path, 'utf8'));
const outputs = new Map();
// Rewrites one generated constant in a page's script; a function replacement, so no "$" in the text is read as a pattern.
const setConstant = (html, name, value) => {
  const pattern = new RegExp(`const ${name} = [\\[{][\\s\\S]*?\\n[\\]}];`);
  if (!pattern.test(html)) throw new Error(`No constant ${name} to write.`);
  return html.replace(pattern, () => `const ${name} = ${JSON.stringify(value, null, 2)};`);
};
const itemSchema = await read('schema/context_item.schema.json');
const traceSchema = await read('schema/trace.schema.json');
const profileSchema = await read('schema/profile.schema.json');
const batchSchema = await read('schema/producer_batch.schema.json');
const conflictGroupSchema = await read('schema/conflict_group.schema.json');
const routePolicySchema = await read('schema/route_policy.schema.json');
const snapshotSchema = await read('schema/snapshot.schema.json');
const registryLockSchema = await read('schema/registry_lock.schema.json');
const conformanceReportSchema = await read('schema/conformance_report.schema.json');
// The planes, slots, item fields, authority values, conflict rules, stages and tests the Spec page lists, in its order.
const model = await read('contract/model.json');
const data = {
  ITEM_SCHEMA: itemSchema,
  TRACE_SCHEMA: traceSchema,
  SLOT_DEFAULTS: await read('contract/slot-defaults.json'),
  REASONS: await read('contract/reasons.json'),
  ITEM_EXAMPLE: await read('examples/context-item.json'),
  TRACE_EXAMPLE: await read('examples/trace.json'),
  PROFILES: await read('examples/profiles.json')
};
outputs.set('generated/contract-data.js', '// Generated by npm run build:contract. Edit schema/, contract/, or examples/.\n' +
  Object.entries(data).map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};`).join('\n') + '\n');
const scaffoldFiles = { ASSEMBLY_SKETCH: 'assembly-sketch.txt', PAYLOAD_TEMPLATE: 'payload.txt', AGENT_GUIDE: 'cwa.md' };
const scaffoldText = await Promise.all(Object.entries(scaffoldFiles).map(async ([name, path]) =>
  `export const ${name} = ${JSON.stringify(await fs.readFile('site/' + path, 'utf8'))};`));
outputs.set('generated/scaffold-text.js', '// Generated by npm run build:contract.\n' + scaffoldText.join('\n') + '\n');
const escapeHtml = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const itemPreview = escapeHtml(JSON.stringify(data.ITEM_EXAMPLE, null, 2));
const producers = await fs.readFile('producers.html', 'utf8');
const failures = data.REASONS.filter(r => r.kind === 'exclusion').map(r => [r.code, r.text, Number(r.rule.slice(2))]);
outputs.set('producers.html', setConstant(producers, 'STAGES', model.stages).replace(/const SLOT_DEFAULTS = \{[\s\S]*?\n\};/,
  `const SLOT_DEFAULTS = ${JSON.stringify(data.SLOT_DEFAULTS, null, 2)};`)
  .replace(/const FAILURES = \[[\s\S]*?\n\];/, `const FAILURES = ${JSON.stringify(failures, null, 2)};`)
  .replace(/<!-- CONTRACT_ITEM_START -->[\s\S]*?<!-- CONTRACT_ITEM_END -->/,
    `<!-- CONTRACT_ITEM_START -->\n<pre style="padding: 18px; overflow: auto; margin: 0;">${itemPreview}</pre>\n<!-- CONTRACT_ITEM_END -->`));
const index = await fs.readFile('index.html', 'utf8');
// The landing page's sample request shows examples/messages-payload.json one member at a time, each text as the model
// receives it, coloured by the plane of the slot the snapshot's profile placed it from.
const payloadBytes = await fs.readFile('examples/messages-payload.json');
const payload = JSON.parse(payloadBytes.toString('utf8'));
const payloadSnapshot = await read('examples/messages-snapshot.json');
if (payloadSnapshot.tokenizer !== 'estimate-utf8/v1') throw new Error('The landing-page payload count supports estimate-utf8/v1 only.');
const planeColor = slot => `var(--p-${{ governance: 'gov', state: 'state', evidence: 'evid', interaction: 'inter' }[slot.split('.')[0]]})`;
const placedBy = wrap => payloadSnapshot.profile.placement.filter(p => p.wrap === wrap).map(p => p.slot);
const memberText = 'style="white-space: pre-wrap; overflow-wrap: anywhere;"';
const memberLabel = (label, margin) => `<div style="font-size: 11px; letter-spacing: 0.12em; text-transform: uppercase; color: var(--muted); margin-bottom: ${margin};">${label}</div>`;
const roleGroup = role => {
  const entries = payload[role];
  const slots = placedBy(role).map(slot => `<span style="color: ${planeColor(slot)};">${slot}</span>`).join(', ');
  const open = entries.length > 1 ? '          <div style="display: flex; flex-direction: column; gap: 6px;">\n' : '          <div>\n';
  return open + `            ${memberLabel(`${role} · ${slots}`, entries.length > 1 ? '0' : '6px')}\n` +
    entries.map((entry, i) => `            <div data-member="${role}/${i}" ${memberText}>${escapeHtml(entry.text)}</div>\n`).join('') + '          </div>\n';
};
// Each tag line is wrapped in a span that also holds its newline: the page's template engine drops
// whitespace-only text between two elements.
const content = escapeHtml(payload.messages[0].content).replace(/^&lt;\/?([A-Za-z_][A-Za-z0-9_.-]*)[^\n]*&gt;\n/gm,
  (line, tag) => `<span style="color: ${planeColor(placedBy('xml:' + tag)[0])};">${line}</span>`);
const messagesGroup = '          <div>\n' + `            ${memberLabel(`messages[0] · role ${payload.messages[0].role}`, '6px')}\n` +
  `            <div data-member="messages/0/content" ${memberText}>${content}</div>\n          </div>\n`;
const payloadTokens = [...payload.system, ...payload.tools].map(e => e.text).concat(payload.messages[0].content)
  .reduce((sum, text) => sum + Math.floor((Buffer.byteLength(text, 'utf8') + 3) / 4), 0);
const payloadHash = createHash('sha256').update(payloadBytes).digest('hex').slice(0, 12);
outputs.set('index.html', index.replace(/<!-- CONTRACT_ITEM_START -->[\s\S]*?<!-- CONTRACT_ITEM_END -->/,
  `<!-- CONTRACT_ITEM_START -->\n<pre style="padding: 20px 18px; overflow: auto; margin: 0;">${itemPreview}</pre>\n<!-- CONTRACT_ITEM_END -->`)
  .replace(/<!-- CONTRACT_PAYLOAD_START -->[\s\S]*?<!-- CONTRACT_PAYLOAD_END -->/,
    `<!-- CONTRACT_PAYLOAD_START -->\n${roleGroup('system')}${roleGroup('tools')}${messagesGroup}<!-- CONTRACT_PAYLOAD_END -->`)
  .replace(/<!-- CONTRACT_PAYLOAD_COUNT_START -->[\s\S]*?<!-- CONTRACT_PAYLOAD_COUNT_END -->/,
    `<!-- CONTRACT_PAYLOAD_COUNT_START --><span>${payloadSnapshot.tokenizer} · ${payloadTokens} input tokens</span><span style="text-transform: none;">sha256 · ${payloadHash}…</span><!-- CONTRACT_PAYLOAD_COUNT_END -->`));

const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv);
ajv.addSchema(itemSchema);
ajv.addSchema(traceSchema);
ajv.addSchema(profileSchema);
ajv.addSchema(batchSchema);
ajv.addSchema(conflictGroupSchema);
ajv.addSchema(routePolicySchema);
ajv.addSchema(snapshotSchema);
ajv.addSchema(registryLockSchema);
ajv.addSchema(conformanceReportSchema);
const source = standalone(ajv, {
  validateItemSchema: itemSchema.$id, validateTraceSchema: traceSchema.$id,
  validateProfileSchema: profileSchema.$id, validateProducerBatchSchema: batchSchema.$id,
  validateConflictGroupSchema: conflictGroupSchema.$id, validateSnapshotSchema: snapshotSchema.$id,
  validateRoutePolicySchema: routePolicySchema.$id, validateRegistryLockSchema: registryLockSchema.$id,
  validateConformanceReportSchema: conformanceReportSchema.$id
});
const bundle = await build({
  stdin: { contents: source, resolveDir: process.cwd(), sourcefile: 'compiled-schemas.js' },
  bundle: true, format: 'esm', platform: 'browser', write: false,
  banner: { js: '// Generated by npm run build:contract. Ajv and ajv-formats: MIT licensed.' }
});
outputs.set('generated/schema-validators.js', bundle.outputFiles[0].text);
const evidence = await fs.readFile('evidence.html', 'utf8');
outputs.set('evidence.html', evidence.replace(/const PROFILES = \[[\s\S]*?\n\];/,
  `const PROFILES = ${JSON.stringify(await read('site/profile-display.json'), null, 2)};`)
  .replace(/const PROFILE_CONTRACTS = \[[\s\S]*?\];/,
    `const PROFILE_CONTRACTS = ${JSON.stringify(data.PROFILES, null, 2)};`));

// The requirement text is authored once and embedded for static hosting.
const requirements = (await read('contract/requirements.json')).sort((a, b) => Number(a.id.slice(2)) - Number(b.id.slice(2)));
// IDs are permanent: new requirements append, and none is renumbered or reused.
if (requirements.some((rule, index) => rule.id !== `R-${index + 1}`)) throw new Error(`Expected permanent requirement IDs R-1 through R-${requirements.length}.`);
const rules = requirements.map(rule => [rule.section, rule.keyword, rule.summary, rule.text]);
// What a reference assembler can verify for each requirement; drives the Assembler page matrix.
const scopes = await read('contract/assembler-scope.json');
if (scopes.length !== requirements.length || scopes.some((row, index) => row.id !== `R-${index + 1}` || !['assembler', 'boundary', 'application'].includes(row.scope) || !row.note)) {
  throw new Error(`contract/assembler-scope.json needs R-1 through R-${requirements.length} in order, each with a scope and a note.`);
}
// Claims imported from the reference assembler (scripts/import-assembler-status.mjs).
const { requirements: statuses } = await read('contract/assembler-status.json');
const allowed = { assembler: ['planned', 'in progress', 'implemented'], boundary: ['planned', 'in progress', 'boundary-checked'], application: ['documented'] };
statuses.forEach((row, i) => {
  if (row.id !== `R-${i + 1}` || !allowed[scopes[i].scope].includes(row.status)) throw new Error(`contract/assembler-status.json: ${row.id} status ${row.status} does not fit scope ${scopes[i].scope}`);
});
if (statuses.length !== requirements.length) throw new Error(`contract/assembler-status.json needs R-1 through R-${requirements.length}.`);
// Each implementation's conformance run, checked against this repo's own cases: a published case the report
// lacks, reports as anything but passed (rejected, for a rejection case), or ran before its files last changed
// does not count (conformance/README.md, Reporting results).
const caseFiles = async dir => (await fs.readdir(dir).catch(() => [])).sort().map(name => `${dir}/${name}/case.json`);
const digests = await caseDigestsNow();
const published = (await Promise.all([...await caseFiles('conformance/cases'), ...await caseFiles('conformance/rejections')].map(read)))
  .map(c => ({ ...c, digest: digests[c.id] }));
const casesFor = id => published.filter(c => c.rules.includes(id));
const runs = await Promise.all(IMPLEMENTATIONS.map(async ({ label, file }) => {
  const { source, cases_at_run: atRun, report } = await read(file);
  if (report === undefined || atRun === undefined) throw new Error(`${file} has no report or cases_at_run; import it with scripts/import-conformance-report.mjs`);
  if (!Array.isArray(source.tags)) throw new Error(`${file} has no source.tags; import it again with scripts/import-conformance-report.mjs`);
  const errors = reportErrors(report);
  if (errors) throw new Error(`${file}: ` + JSON.stringify(errors));
  return { label, source, report, outcomes: tally(report, atRun, published) };
}));
const conformance = runs.map(({ label, source, report, outcomes }) => ({
  label, name: report.implementation.name, version: report.implementation.version, repository: source.repository,
  sha: source.commit, tags: source.tags, websiteSha: ranAt(report), total: published.length,
  passed: [...outcomes.values()].filter(o => o === 'passed').length, stale: [...outcomes.values()].filter(o => o === 'stale').length,
}));
for (const page of ['spec.html', 'assembler.html']) {
  const html = await fs.readFile(page, 'utf8');
  const rows = page === 'spec.html' ? rules : rules.map((r, i) => [r[1], r[2], scopes[i].scope, scopes[i].note, statuses[i].status,
    casesFor(`R-${i + 1}`).length, runs.map(run => casesFor(`R-${i + 1}`).filter(c => run.outcomes.get(c.id) === 'passed').length)]);
  let updated = html.replace(/const RULES = \[[\s\S]*?\n\];/, `const RULES = ${JSON.stringify(rows, null, 2)};`);
  if (page === 'assembler.html') updated = updated.replace(/const CONFORMANCE = [\[{][\s\S]*?[\]}];/, `const CONFORMANCE = ${JSON.stringify(conformance)};`);
  if (page === 'spec.html') {
    for (const [name, value] of Object.entries({ PLANES: model.planes, SLOTS: model.slots, AUTHORITY: model.authority,
      CONFLICTS: model.conflicts, STAGES: model.stages, ITEM_FIELDS: model.item_fields, TESTS: model.tests })) updated = setConstant(updated, name, value);
    const profile = JSON.stringify(data.PROFILES[0], null, 2).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
    updated = updated.replace(/<!-- CONTRACT_PROFILE_START -->[\s\S]*?<!-- CONTRACT_PROFILE_END -->/,
      `<!-- CONTRACT_PROFILE_START -->\n          <pre style="padding: 18px; overflow: auto; margin: 0;">${profile}</pre>\n          <!-- CONTRACT_PROFILE_END -->`);
  }
  outputs.set(page, updated);
}
// SPEC.md is written from the Spec page as this build leaves it, so its requirements and profile are the current ones.
const site = `https://${(await fs.readFile('CNAME', 'utf8')).trim()}/`;
outputs.set('SPEC.md', specMarkdown({ html: outputs.get('spec.html'), requirements, site }));

// llms.txt indexes the site for language models. The producer and assembler guides are written by hand around tables
// generated here, and llms-full.txt joins all three with spec §1, the slots and authority values, every requirement
// and the conformance README, so that one file holds the whole contract.
const specHtml = await fs.readFile('spec.html', 'utf8');
const slotOrder = Object.keys(data.SLOT_DEFAULTS);
if (model.slots.length !== slotOrder.length || model.slots.some(s => !slotOrder.includes(s.id))) throw new Error('contract/model.json slots must name every slot in contract/slot-defaults.json.');
const planeOf = slot => model.planes.find(p => p.id === slot.split('.')[0]);
const codeSpan = text => '`' + text + '`';
const mdTable = (head, rows) => [head, head.map(() => '---'), ...rows]
  .map(row => `| ${row.map(c => String(c).replaceAll('|', '\\|')).join(' | ')} |`).join('\n');
const reasonTable = kind => mdTable(['Code', 'Rule', 'When'], data.REASONS.filter(r => r.kind === kind).map(r => [codeSpan(r.code), r.rule, r.text]));
const githubTree = repository => `https://github.com/${repository}`;
const llmsBlocks = {
  STAGES: model.stages.map(({ name, owner, text }, i) => `${i + 1}. ${name} (${owner}): ${text}`).join('\n'),
  BATCH: '```json\n' + JSON.stringify(await read('examples/producer-batch.json'), null, 2) + '\n```',
  SLOTS: mdTable(['Slot', 'Plane', 'Holds', 'Authority', 'Tier', 'Lineage', 'injection_risk', 'conflict_policy'], slotOrder.map(slot => {
    const d = data.SLOT_DEFAULTS[slot];
    return [codeSpan(slot), planeOf(slot).name, model.slots.find(s => s.id === slot).holds, codeSpan(d.authority), d.tier, d.lineage, d.injection_risk, d.conflict_policy];
  })),
  AUTHORITY: mdTable(['Authority', 'Role', 'Meaning'], model.authority.map(({ name, value, text }) => [codeSpan(value), name, text])),
  EXCLUSIONS: reasonTable('exclusion'),
  REFUSALS: reasonTable('refusal'),
  SCOPE: mdTable(['Rule', 'Summary', 'Scope', 'What an assembler checks'], requirements.map((r, i) => [r.id, r.summary, scopes[i].scope, scopes[i].note])),
  IMPLEMENTATIONS: mdTable(['Language', 'Package', 'Repository', 'Commit', 'Published cases and rejections', 'Contract vendored at'], conformance.map(c => [
    c.label, `${codeSpan(c.name)} ${c.version}`, githubTree(c.repository),
    `${codeSpan(c.sha.slice(0, 7))}${c.tags.length ? ' (' + c.tags.join(', ') + ')' : ''}`,
    `${c.passed} of ${c.total} pass${c.stale ? `; ${c.stale} changed since its run` : ''}`,
    `website ${codeSpan(c.websiteSha.slice(0, 7))}`]))
};
const fillBlocks = text => text.replace(/<!-- CONTRACT_([A-Z_]+)_START -->\n[\s\S]*?<!-- CONTRACT_\1_END -->/g, (block, name) => {
  if (!(name in llmsBlocks)) throw new Error(`No generated block named ${name}.`);
  return `<!-- CONTRACT_${name}_START -->\n${llmsBlocks[name]}\n<!-- CONTRACT_${name}_END -->`;
});
const guides = {};
for (const path of ['llms-producers.txt', 'llms-assemblers.txt']) {
  guides[path] = fillBlocks(await fs.readFile(path, 'utf8'));
  outputs.set(path, guides[path]);
}
// A file joins llms-full.txt under a heading of its own: its title line goes, its headings drop one level, and the
// block markers go, so the file reads as one document.
const nest = (heading, text) => {
  let fenced = false;
  const body = text.replace(/^# .*\n/, '').replace(/^<!-- CONTRACT_[A-Z_]+_(START|END) -->\n/gm, '').split('\n').map(line => {
    if (line.startsWith('```')) fenced = !fenced;
    return !fenced && /^#{1,5} /.test(line) ? '#' + line : line;
  }).join('\n');
  return `## ${heading}\n${body.trimEnd()}\n`;
};
const decodeHtml = text => text.replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&quot;', '"').replaceAll('&amp;', '&');
const conformanceSection = specHtml.match(/<section id="s1">([\s\S]*?)<\/section>/)[1];
const conformanceText = [...conformanceSection.matchAll(/<p[^>]*>([\s\S]*?)<\/p>/g)]
  .map(m => decodeHtml(m[1].replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim());
if (conformanceText.length === 0) throw new Error('spec.html section 1 has no paragraphs.');
const planes = model.planes.map(plane => `### ${plane.name}: ${plane.answers}\n\n` + model.slots.filter(s => planeOf(s.id) === plane)
  .map(({ id, holds, rule }) => `- ${codeSpan(id)}: ${holds} ${rule}`).join('\n')).join('\n\n');
outputs.set('llms-full.txt', [
  '# Context Window Architecture: the full contract\n\n' +
  '> Everything an AI agent needs to write a producer for, implement, or build an application on Context Window Architecture (CWA), a draft specification for assembling every model call from typed slots, in one file. ' +
  'It is generated from the website repository by npm run build:contract: llms.txt, spec §1 and the slots and authority values from the Spec page, the producer and assembler guides, ' +
  'every requirement from contract/requirements.json, and conformance/README.md. Where anything here disagrees with the Spec page, the Spec page holds.\n',
  nest('Orientation (llms.txt)', await fs.readFile('llms.txt', 'utf8')),
  '## Conformance (spec §1)\n\n' + conformanceText.join('\n\n') + '\n',
  '## Planes, slots and authority values (spec §2 and §3.1)\n\n' +
  'A model call is assembled from items. Every item belongs to exactly one slot, and slots are grouped into four planes, which answer four different questions and are never merged. ' +
  'Each slot takes the authority its defaults name (R-1); the producer guide below has the full table of defaults.\n\n' + planes + '\n\n' +
  '### Authority values\n\n' + llmsBlocks.AUTHORITY + '\n',
  nest('Producers (llms-producers.txt)', guides['llms-producers.txt']),
  nest('Assemblers (llms-assemblers.txt)', guides['llms-assemblers.txt']),
  `## Requirements R-1 to R-${requirements.length} (contract/requirements.json)\n\n` +
  requirements.map(r => `### ${r.id}: ${r.summary}\n\n${r.text}\n`).join('\n'),
  nest('Conformance cases (conformance/README.md)', await fs.readFile('conformance/README.md', 'utf8'))
].join('\n'));

for (const [path, content] of outputs) {
  if (check) {
    const existing = await fs.readFile(path, 'utf8').catch(() => null);
    if (existing !== content) throw new Error(`${path} is stale; run npm run build:contract`);
  } else await fs.writeFile(path, content);
}
console.log(`${check ? 'Checked' : 'Generated'} ${outputs.size} contract artifacts.`);
